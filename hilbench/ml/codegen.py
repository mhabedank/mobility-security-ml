"""Emit C sources (model_zoo.h / model_zoo.c) for microinfer from QModels."""
from __future__ import annotations

from pathlib import Path

import numpy as np

from .model import OPS, QModel

HEADER = "/* AUTO-GENERATED by hilbench.ml.codegen - do not edit. */\n"


def _ident(name: str) -> str:
    return "".join(c if c.isalnum() else "_" for c in name)


def _array(ctype: str, name: str, values: np.ndarray, per_line: int = 24) -> str:
    vals = [str(int(v)) for v in np.asarray(values).reshape(-1)]
    if ctype == "int32_t":
        # INT32_MIN cannot be written as a plain literal.
        vals = ["(-2147483647 - 1)" if v == "-2147483648" else v for v in vals]
    lines = [", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    body = ",\n    ".join(lines) if lines else "0"
    size = max(len(vals), 1)
    return f"static const {ctype} {name}[{size}] MI_CONST = {{\n    {body}\n}};\n"


def model_to_c(model: QModel) -> str:
    m = _ident(model.name)
    out = [f"/* {model.name}: {model.description} */\n"]
    layer_rows = []
    for i, l in enumerate(model.layers):
        p = f"{m}_l{i}"
        if l.has_params:
            out.append(_array("int8_t", f"{p}_w", l.weights.astype(np.int8)))
            if l.bias is not None:
                out.append(_array("int32_t", f"{p}_b", l.bias.astype(np.int32)))
            out.append(_array("int32_t", f"{p}_m", l.mult.astype(np.int32)))
            out.append(_array("int8_t", f"{p}_s", l.shift.astype(np.int8)))
            refs = (f"{p}_w", f"{p}_b" if l.bias is not None else "NULL", f"{p}_m", f"{p}_s")
            n_mult = int(l.mult.size)
        else:
            refs = ("NULL", "NULL", "NULL", "NULL")
            n_mult = 0
        if l.op == "dense":
            in_hwc = (1, 1, int(np.prod(l.in_shape)))
            out_hwc = (1, 1, int(np.prod(l.out_shape)))
        else:
            in_hwc, out_hwc = l.in_shape, l.out_shape
        layer_rows.append(
            "    {{ {op}, {kh}, {kw}, {sh}, {sw}, {pt}, {pl}, {fl}, {ih}, {iw}, {ic}, {oh}, {ow}, {oc}, "
            "{izp}, {ozp}, {amin}, {amax}, {nm}, {w}, {b}, {mu}, {sh_} }}".format(
                op=f"MI_OP_{l.op.upper()}", kh=l.kernel[0], kw=l.kernel[1], sh=l.stride[0],
                sw=l.stride[1], pt=l.pad[0], pl=l.pad[1],
                fl="MI_FLAG_SINGLE_ROUNDING" if l.rounding == "single" else 0, ih=in_hwc[0], iw=in_hwc[1], ic=in_hwc[2],
                oh=out_hwc[0], ow=out_hwc[1], oc=out_hwc[2], izp=l.in_zp, ozp=l.out_zp,
                amin=l.act_min, amax=l.act_max, nm=n_mult, w=refs[0], b=refs[1], mu=refs[2], sh_=refs[3]))
    out.append(f"static const mi_layer_t {m}_layers[{len(model.layers)}] = {{\n" + ",\n".join(layer_rows) + "\n};\n")
    n_tests = int(model.test_inputs.shape[0])
    out.append(_array("int8_t", f"{m}_test_in", model.test_inputs.astype(np.int8)))
    out.append(_array("int8_t", f"{m}_test_out", model.test_outputs.astype(np.int8)))
    desc = model.description.replace("\\", "\\\\").replace('"', '\\"')
    out.append(
        f"const mi_model_t mi_model_{m} = {{\n"
        f"    \"{model.name}\", \"{desc}\", {len(model.layers)}, {m}_layers,\n"
        f"    {model.in_size}u, {model.out_size}u, {model.arena_size()}u, {model.param_bytes()}u,\n"
        f"    {model.macs()}u, 0x{model.crc32():08x}u, {n_tests}, {m}_test_in, {m}_test_out\n}};\n")
    return "".join(out)


def zoo_sources(models: list[QModel]) -> tuple[str, str]:
    for model in models:
        for l in model.layers:
            if l.op not in OPS:
                raise ValueError(f"{model.name}: unsupported op {l.op}")
    arena = max(m.arena_size() for m in models)
    max_in = max(m.in_size for m in models)
    max_out = max(m.out_size for m in models)
    h = [HEADER, "#ifndef MODEL_ZOO_H\n#define MODEL_ZOO_H\n\n#include \"microinfer.h\"\n\n",
         "#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n",
         f"#define MI_ZOO_ARENA_SIZE {arena}u\n#define MI_ZOO_MAX_IN {max_in}u\n#define MI_ZOO_MAX_OUT {max_out}u\n\n"]
    for m in models:
        h.append(f"extern const mi_model_t mi_model_{_ident(m.name)};\n")
    h.append("\n/* NULL-terminated; models can be dropped with -DMI_EXCLUDE_<NAME>. */\n")
    h.append("extern const mi_model_t *const mi_zoo[];\nextern const unsigned mi_zoo_count;\n\n")
    h.append("#ifdef __cplusplus\n}\n#endif\n\n#endif /* MODEL_ZOO_H */\n")

    c = [HEADER, "#include \"model_zoo.h\"\n\n#include <stddef.h>\n\n"]
    for m in models:
        guard = f"MI_EXCLUDE_{_ident(m.name).upper()}"
        c.append(f"#ifndef {guard}\n{model_to_c(m)}#endif /* {guard} */\n\n")
    c.append("const mi_model_t *const mi_zoo[] = {\n")
    for m in models:
        guard = f"MI_EXCLUDE_{_ident(m.name).upper()}"
        c.append(f"#ifndef {guard}\n    &mi_model_{_ident(m.name)},\n#endif\n")
    c.append("    NULL\n};\n\nconst unsigned mi_zoo_count = sizeof(mi_zoo) / sizeof(mi_zoo[0]) - 1u;\n")
    return "".join(h), "".join(c)


def write_zoo_sources(models: list[QModel], out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    h, c = zoo_sources(models)
    (out_dir / "model_zoo.h").write_text(h)
    (out_dir / "model_zoo.c").write_text(c)
